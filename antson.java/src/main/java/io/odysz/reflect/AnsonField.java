package io.odysz.reflect;

import java.util.ArrayList;

import io.odysz.anson.Anson;

/**
 * A field of {@link AnsonAst#fields}, the Java peer of anson.cmake's AnsonField (anson.h).
 * 
 * <p>Not to be confused with the annotation io.odysz.anson.AnsonField.</p>
 * 
 * @since 1.2.0
 */
public class AnsonField extends Anson {
	public String fieldname;

	/**
	 * The field's type in AST syntax: string, int, boolean, ..., VarType (Object),
	 * list&lt;E (lists, sets and arrays), map&lt;K, V, or a qualified name,
	 * e.g. map&lt;string, list&lt;io.oz.x.Doc.Kind
	 */
	public String dataAnclass;

	/**
	 * Element type of a list, or value type of a map, in AST syntax, e.g. list&lt;io.oz.x.Doc.Kind
	 * for map&lt;string, list&lt;io.oz.x.Doc.Kind
	 */
	public String valType;

	/////////////////// java only, generated by anson.reflect ////////////////////
	/** e.g. ["protected", "static", "final"]; package private: [] */
	public ArrayList<String> modifiers;

	/** Annotations on the field, both RUNTIME and CLASS retention. */
	public ArrayList<AnAnnotation> annotations;

	public AnsonField() { }

	/**
	 * @param fieldname
	 * @param modifiers
	 */
	public AnsonField(String fieldname, ArrayList<String> modifiers) {
		this.fieldname = fieldname;
		this.modifiers = modifiers;
		this.annotations = new ArrayList<AnAnnotation>();
	}
}
