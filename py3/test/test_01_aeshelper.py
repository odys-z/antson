"""
The py3 peer's version of anson.cmake/tests/t01_aeshelper.cpp.

Java cases run AESHelper2.main() of semantic.transact's jar with dependencies, of version
transact_ver, installed in the local maven repository, e.g.
    semantic.transact$ mvn install
or semantic-jserv/jserv-album$ invoke install-maven-local.
The Java cases fail if it is not installed.

Cases of fixed vectors (known key, iv, plain text and cipher, from the Java, C++ & TS tests) need no Java.

Run in py3: python -m unittest test.test_01_aeshelper
"""
import json
import os
import re
import subprocess
import unittest
from pathlib import Path
from typing import Optional

from src.anson.io.odysz.aes2 import AESHelper2
from src.anson.io.odysz.common import mvn

transact = 'io.github.odys-z:semantics.transact'
transact_ver = '[1.5.78,)'

key = "Героям слава!"
slava_ukraini = "Слава Україні!"

jar: Optional[Path] = None


def show(case: str, **pairs: str):
    """
    Print the case's key, iv, plain text, cipher, etc. for a glance.
    """
    print(f'\n[{case}]')
    for k, v in pairs.items():
        print(f'  {k:<8}: {v}')


def java(*args: str) -> str:
    """
    Run AESHelper2.main(args) of the jar, the same as the c++ test.
    :return: stdout
    """
    p = subprocess.run(['java', '-Dfile.encoding=UTF-8', '-Dstdout.encoding=UTF-8', '-jar', jar, *args],
                       capture_output=True, encoding='utf-8')
    if p.returncode != 0:
        raise AssertionError(f'Java process failed: {p.returncode}\n{p.stderr}')
    return p.stdout


class AESHelperVectorsTest(unittest.TestCase):
    """
    Fixed vectors generated by Java (semantic-transact AESHelperTest) and anson.cmake t01,
    the same as Anclient/js/semantier/test/00.2-aes2.mocha.ts.
    """

    def test_decrypt(self):
        for iv64, cipher in [("98Q1sXoSS0Ry4CooJYy/tg==", "q6vt9EfQZD3Oc/Pf4tICD5tSHpprYy4j1GcrWkFQ8iE="),
                             ("NXAKQcZGUk3E4pLm1iP4yA==", "nPf99DNPI1gvzL3HGicg0kdGJgAo3L0zMUbS90ReCto=")]:
            plain = AESHelper2.decrypt(cipher, key, AESHelper2.decode64(iv64))
            show('vectors: decrypt', key=key, iv=iv64, cipher=cipher, plain=plain)
            self.assertEqual(slava_ukraini, plain)

    def test_encrypt(self):
        for iv64, expect in [("J/r4ACTePjQWSR1KuWBRKQ==", "a2zlaOo8fPoBUBU90n3LZzabRsoSzYOKtF1JTsR2Nv4="),
                             ("c+r+6moOay+4VadcEkveNg==", "ZAFqxw+z62DQJXZYv26+wkXPi5UP8bCkSlTpiQcYKwM=")]:
            cipher = AESHelper2.encrypt(slava_ukraini, key, AESHelper2.decode64(iv64))
            show('vectors: encrypt', key=key, iv=iv64, plain=slava_ukraini, cipher=cipher, expect=expect)
            self.assertEqual(expect, cipher)

    def test_wrong_key(self):
        iv = AESHelper2.decode64("98Q1sXoSS0Ry4CooJYy/tg==")
        with self.assertRaises(ValueError):
            AESHelper2.decrypt("q6vt9EfQZD3Oc/Pf4tICD5tSHpprYy4j1GcrWkFQ8iE=", "123456", iv)

    def test_repack_token(self):
        uid, pswd = "ody", "123456"

        repacked = AESHelper2.repackSessionToken(
            "ie6uHYaAxUzTdkOZvagpXhopWTAMiqD14Jd1jkNgFdU=:97zMIGYPh/3+QUpqmaNY4A==", pswd, uid,
            AESHelper2.decode64('JoFabRnGRbYbc++Q4jlaQg=='))
        self.assertEqual('ym/5XXBp9YSH5TDRcQmIOMXpCy+mACbf2AdhCo1rr6I=:JoFabRnGRbYbc++Q4jlaQg==', repacked)
        self.assertTrue(AESHelper2.verifyToken(repacked, 'SHXoqfN2CeiChANHFBsd4Q==', uid, pswd))

        repacked = AESHelper2.repackSessionToken(
            "1OYj0I+b06C43roM7SsnghQChQ7JsvmBBZ7SoJctXX8=:9TgsimQd3Pv7+4u+nhZywQ==", pswd, uid,
            AESHelper2.decode64('T6AIbzvfDf8IMp6474a1VQ=='))
        self.assertEqual("ChzT01BOTnMLkvfmXmwD5QWSUfC3dF59bBWR0xtarYg=:T6AIbzvfDf8IMp6474a1VQ==", repacked)
        self.assertTrue(AESHelper2.verifyToken(repacked, 'LipVxlQC7sHiSsWrgjTGPQ==', uid, pswd))

    def test_session_key(self):
        """
        Java AESHelperTest.testSessionToken()
        """
        uid, pswd = "ody", "io.github.odys-z"
        token, knows = AESHelper2.packSessionKey(pswd)
        self.assertEqual(24, len(knows))
        self.assertEqual(69, len(token))  # 44 + 1 + 24

        self.assertTrue(AESHelper2.verifyToken(AESHelper2.repackSessionToken(token, pswd, uid), knows, uid, pswd))

        ssToken_by_serv = "9ewQrDgVif1TRw58GxlIE7WXd8gxSx/wGefA32081uA=:P8Lz+vcOn5f6vskPWs4mXA=="
        ss = ssToken_by_serv.split(':')
        knows = AESHelper2.decrypt(ss[0], "123456", AESHelper2.decode64(ss[1]))
        request = AESHelper2.repackSessionToken(ssToken_by_serv, "123456", "ody")
        self.assertTrue(AESHelper2.verifyToken(request, knows, "ody", "123456"))


class AESHelperJavaTest(unittest.TestCase):
    """
    The same cases as anson.cmake/tests/t01_aeshelper.cpp, against Java AESHelper2.main().
    """

    @classmethod
    def setUpClass(cls):
        global jar
        ver = mvn.requir_installed(transact, transact_ver, tolerate=True)
        if ver is None:
            raise AssertionError(f'{transact} {transact_ver} is not installed.')

        group, artifact = transact.split(':')
        jar = mvn.local_repository().joinpath(*group.split('.'), artifact, ver,
                                              f'{artifact}-{ver}-jar-with-dependencies.jar')
        if not jar.is_file():
            raise AssertionError(f'{jar} is not installed.')

    def test_base64(self):
        iv = AESHelper2.getRandom()
        ivbytes = 'iv-bytes.bin'
        with open(ivbytes, 'wb') as f:
            f.write(iv)

        b64 = java('encode64', ivbytes)
        self.assertEqual(AESHelper2.encode64(iv), b64)

        java('decode64', b64, ivbytes)
        with open(ivbytes, 'rb') as f:
            self.assertEqual(iv, f.read(), 'Binary mismatch after Java decode64 cycle')
        os.remove(ivbytes)

    def test_decrypt(self):
        output = java('encrypt', key, slava_ukraini)
        self.assertRegex(output, r're-decrpyted:\s+' + slava_ukraini)

        cipher = re.search(r'cipher:\s*(.*)', output).group(1).strip()
        iv = re.search(r'iv:\s*(.+)', output).group(1).strip()
        plain = AESHelper2.decrypt(cipher, key, AESHelper2.decode64(iv))
        show('java encrypt -> py3 decrypt', key=key, iv=iv, cipher=cipher, plain=plain)
        self.assertEqual(slava_ukraini, plain)

    def test_encrypt(self):
        iv = AESHelper2.getRandom()
        cipher = AESHelper2.encrypt(slava_ukraini, key, iv)

        output = java('decrypt', key, AESHelper2.encode64(iv), cipher)
        m = re.search(r'plain:\s*(.*)', output)
        show('py3 encrypt -> java decrypt', key=key, iv=AESHelper2.encode64(iv), plain=slava_ukraini,
             cipher=cipher, java=m.group(1).strip() if m else output)
        self.assertRegex(output, r'plain:\s+' + slava_ukraini)

    def test_verify_token(self):
        uid, pswd = "ody", "123456"
        ssinf = json.loads(java('login', uid, pswd))  # SessionInf

        ss = ssinf['ssToken'].split(':')
        knows = AESHelper2.decrypt(ss[0], pswd, AESHelper2.decode64(ss[1]))

        token = AESHelper2.repackSessionToken(ssinf['ssToken'], pswd, uid)
        verified = java('verify', ssinf['uid'], pswd, token, knows)
        show('java login -> py3 repack -> java verify', uid=uid, pswd=pswd,
             ssToken=ssinf['ssToken'], knows=knows, token=token, verify=verified)
        self.assertEqual("OK", verified)


if __name__ == '__main__':
    unittest.main()
