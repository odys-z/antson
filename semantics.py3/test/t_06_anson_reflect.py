from typing import cast
from unittest import TestCase

from anson.io.odysz.anson import Anson

from semanticshare.io.odysz.reflect import AnsonTypes, AnsonAst, AnsonField, AnAnnotation, AnValue


class AnsonReflectTest(TestCase):
    '''
    t_06-anson-types.json: generated by antson/anson.reflect's AnsonTypesMojoTest,
    for the test types io.oz.anson.reflect.ttypes.
    '''

    def test_(self):
        tt = 'io.oz.anson.reflect.ttypes.'
        t = cast(AnsonTypes, Anson.from_file('test/t_06-anson-types.json'))

        self.assertIsInstance(t, AnsonTypes)
        self.assertEqual('io.github.odys-z:anson-test-types:0.0.1', t.module)
        self.assertEqual(8, len(t.asts))
        self.assertEqual('io.github.odys-z:antson:1.2.0', t.dependencies['io.odysz.anson.AnsonField'])

        ta = t.asts[tt + 'TArrays']
        self.assertIsInstance(ta, AnsonAst)
        self.assertEqual('class', ta.kind)
        self.assertEqual(tt + 'TArrays', ta.dataAnclass)
        self.assertEqual('io.odysz.anson.Anson', ta.baseAnclass)
        self.assertTrue(ta.isJsonable)
        self.assertIn('io.odysz.anson.AnsT4Enum.MsgCode', ta.uses)
        self.assertEqual(['protected', 'static'], t.asts[tt + 'TArrays.Prot'].modifiers)

        self.assertEqual({'cube', 'ints', 'codes', 'arrs', 'lists', 'port', 'parent', 'pkgMap', 'CONST', 'counter'},
                         set(ta.fields))
        self.assertIsInstance(ta.fields['cube'], AnsonField)
        self.assertEqual('list<list<list<io.odysz.anson.AnsT2', ta.fields['cube'].dataAnclass)
        self.assertEqual('map<string, list<io.odysz.anson.AnsT4Enum.MsgCode', ta.fields['codes']['dataAnclass'],
                         "as cpp_generator reads fd['dataAnclass']")
        self.assertEqual('list<io.odysz.anson.AnsT4Enum.MsgCode', ta.fields['codes'].valType)
        self.assertEqual([], ta.fields['pkgMap'].modifiers)

        k = t.asts[tt + 'TArrays.Kind']
        self.assertTrue(k.isEnum)
        self.assertEqual({'a': 0, 'b': 1}, k.enums)

        # @AnsonField(ignoreTo = true, ref = AnsonField.enclosing)
        a = ta.fields['parent'].annotations[0]
        self.assertIsInstance(a, AnAnnotation)
        self.assertEqual('io.odysz.anson.AnsonField', a.annotation)
        self.assertTrue(a.runtime)
        self.assertEqual(('boolean', 'true'), (a.element('ignoreTo').valType, a.element('ignoreTo').value))
        self.assertIsNone(a.element('ignoreFrom'))

        # @TAnno(value = "pkg", kinds = {Kind.a, Kind.b}, type = AnsT3.class, nums = {1, 2})
        p = ta.fields['pkgMap'].annotations[0]
        self.assertFalse(p.runtime)
        self.assertIsInstance(p.element('type'), AnValue)
        self.assertEqual(('java.lang.Class', 'io.odysz.anson.AnsT3'), (p.element('type').valType, p.element('type').value))
        self.assertEqual([tt + 'TArrays.Kind.a', tt + 'TArrays.Kind.b'], p.element('kinds').array)
        self.assertEqual(['1', '2'], p.element('nums').array)

        self.assertEqual([tt + 'TArrays.Kind'], t.simple_names()['Kind'])
